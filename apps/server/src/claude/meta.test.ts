import { after, test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { HEAD_MAX_LINES, TAIL_BYTES, newReadCounters, readTranscriptMeta } from "./meta.ts";

const tmpDirs: string[] = [];
after(async () => {
  for (const d of tmpDirs) await fs.rm(d, { recursive: true, force: true });
});

async function tmpFile(name = "s.jsonl"): Promise<string> {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), "claude-meta-"));
  tmpDirs.push(dir);
  return path.join(dir, name);
}

const jl = (objs: object[]): string => objs.map((o) => JSON.stringify(o) + "\n").join("");

const user = (content: unknown, extra: object = {}) => ({
  type: "user",
  message: { role: "user", content },
  timestamp: "2026-11-15T10:00:00.000Z",
  ...extra,
});

/** A line of about `bytes` bytes that carries no field the reader looks for. */
const filler = (i: number, bytes = 200) => ({ type: "attachment", n: i, pad: "x".repeat(bytes) });

test("small file: first cwd/entrypoint/timestamp, last custom-title and ai-title", async () => {
  const file = await tmpFile();
  await fs.writeFile(
    file,
    jl([
      { type: "custom-title", customTitle: "first-name" },
      { type: "ai-title", aiTitle: "first-ai" },
      { type: "attachment", cwd: "/work/a", entrypoint: "cli", timestamp: "2026-11-15T01:02:03.000Z" },
      { type: "attachment", cwd: "/work/b", entrypoint: "sdk-ts", timestamp: "2026-11-15T09:00:00.000Z" },
      { type: "custom-title", customTitle: "second-name" },
      { type: "ai-title", aiTitle: "second-ai" },
    ]),
  );
  const c = newReadCounters();
  const e = await readTranscriptMeta(file, undefined, c);
  assert.ok(e);
  const st = await fs.stat(file);
  assert.equal(e.meta.cwd, "/work/a");
  assert.equal(e.meta.entrypoint, "cli");
  assert.equal(e.meta.createdAt, Date.parse("2026-11-15T01:02:03.000Z"));
  assert.equal(e.meta.name, "second-name");
  assert.equal(e.meta.title, "second-ai");
  assert.equal(e.meta.updatedAt, Math.floor(st.mtimeMs));
  assert.equal(e.meta.sizeBytes, st.size);
  assert.equal(e.headComplete, false, "the head ran to EOF");
});

test("large file: the tail wins per field, the head fills a field the tail lacks", async () => {
  const file = await tmpFile();
  const head = [
    { type: "custom-title", customTitle: "head-name" },
    { type: "ai-title", aiTitle: "head-ai" },
    ...Array.from({ length: HEAD_MAX_LINES + 10 }, (_, i) => filler(i)),
  ];
  // A title that sits only in the middle (outside head and tail) is not seen.
  const middle = [{ type: "ai-title", aiTitle: "middle-ai" }, ...Array.from({ length: 300 }, (_, i) => filler(i))];
  const tail = [{ type: "ai-title", aiTitle: "tail-ai" }, filler(1)];
  await fs.writeFile(file, jl([...head, ...middle, ...tail]));
  const e = await readTranscriptMeta(file, undefined, newReadCounters());
  assert.ok(e);
  assert.equal(e.meta.name, "head-name", "no custom-title in the tail, so the head's stays");
  assert.equal(e.meta.title, "tail-ai");

  // A later custom-title in the tail wins over the head's, and an empty one clears the name.
  await fs.appendFile(file, jl([{ type: "custom-title", customTitle: "tail-name" }]));
  const e2 = await readTranscriptMeta(file, e, newReadCounters());
  assert.equal(e2?.meta.name, "tail-name");
  await fs.appendFile(file, jl([{ type: "custom-title", customTitle: "" }]));
  const e3 = await readTranscriptMeta(file, e2 ?? undefined, newReadCounters());
  assert.equal(e3?.meta.name, null);
});

test("preview skips tool results, wrappers and isMeta lines, and is clipped to 200 chars", async () => {
  const file = await tmpFile();
  const real = "  실제 프롬프트 " + "가".repeat(400);
  await fs.writeFile(
    file,
    jl([
      user([{ type: "tool_result", tool_use_id: "t1", content: "tool output" }]),
      user("<command-name>/model</command-name>"),
      user("<command-message>model</command-message>"),
      user("<local-command-stdout>ok</local-command-stdout>"),
      user("<local-command-caveat>Caveat: ...</local-command-caveat>"),
      user("<system-reminder>x</system-reminder>"),
      user("Caveat: The messages below were generated by the user while running local commands."),
      user("[Request interrupted by user]"),
      user("This session is being continued from a previous conversation that ran out of context."),
      user("<persisted-output>x</persisted-output>"),
      user("<task-notification> <task-id>abc</task-id></task-notification>"),
      user("Continue from where you left off.", { isMeta: true }),
      user([{ type: "text", text: "   " }]),
      user([
        { type: "image", source: {} },
        { type: "text", text: real },
      ]),
      user("second prompt"),
    ]),
  );
  const e = await readTranscriptMeta(file, undefined, newReadCounters());
  assert.ok(e?.meta.preview);
  assert.ok(e.meta.preview.startsWith("실제 프롬프트 "), e.meta.preview);
  assert.equal(Array.from(e.meta.preview).length, 200);
});

test("preview clipping never splits a surrogate pair", async () => {
  const file = await tmpFile();
  const smile = String.fromCodePoint(0x1f600);
  await fs.writeFile(file, jl([user(smile.repeat(300))]));
  const e = await readTranscriptMeta(file, undefined, newReadCounters());
  assert.equal(e?.meta.preview, smile.repeat(200));
});

test("a giant line in the middle is never read", async () => {
  const file = await tmpFile();
  const giant = JSON.stringify({ type: "assistant", blob: "y".repeat(16 * 1024 * 1024) }) + "\n";
  const fh = await fs.open(file, "w");
  await fh.write(jl([{ type: "x", cwd: "/w", timestamp: "2026-11-15T00:00:00Z" }, ...Array.from({ length: HEAD_MAX_LINES + 5 }, (_, i) => filler(i))]));
  await fh.write(giant);
  await fh.write(jl([{ type: "custom-title", customTitle: "after-giant" }, { type: "ai-title", aiTitle: "ai-after-giant" }, filler(0)]));
  await fh.close();
  const size = (await fs.stat(file)).size;
  const c = newReadCounters();
  const e = await readTranscriptMeta(file, undefined, c);
  assert.equal(e?.meta.name, "after-giant");
  assert.equal(e?.meta.cwd, "/w");
  assert.ok(size > 16 * 1024 * 1024);
  // head (~125 short lines) + at most one 64KB chunk past it + the tail window. Both titles sit
  // after the giant line, so the backward title search stops before reaching it.
  assert.ok(c.bytesRead < 200 * 1024, `read ${c.bytesRead} of ${size} bytes`);
});

test("a giant last line leaves the tail without a line; the head's titles stand", async () => {
  const file = await tmpFile();
  await fs.writeFile(
    file,
    jl([
      { type: "custom-title", customTitle: "head-name" },
      ...Array.from({ length: HEAD_MAX_LINES + 5 }, (_, i) => filler(i)),
      { type: "assistant", blob: "z".repeat(TAIL_BYTES * 3) },
    ]),
  );
  const c = newReadCounters();
  const e = await readTranscriptMeta(file, undefined, c);
  assert.equal(e?.meta.name, "head-name");
  assert.equal(c.tailsWithoutLine, 1);
  assert.equal(c.badJsonLines, 0, "the fragment at the window start is dropped, not parsed");
});

test("cache: unchanged file is a hit; an appended file reuses the head and reads only the tail", async () => {
  const file = await tmpFile();
  await fs.writeFile(file, jl(Array.from({ length: HEAD_MAX_LINES * 4 }, (_, i) => filler(i, 1000))));
  const c = newReadCounters();
  const e1 = await readTranscriptMeta(file, undefined, c);
  assert.ok(e1?.headComplete);
  const afterFirst = c.bytesRead;

  const e2 = await readTranscriptMeta(file, e1, c);
  assert.equal(e2, e1);
  assert.equal(c.cacheHits, 1);
  assert.equal(c.bytesRead, afterFirst, "a cache hit reads no content");

  await fs.appendFile(file, jl([{ type: "ai-title", aiTitle: "appended" }]));
  const e3 = await readTranscriptMeta(file, e2 ?? undefined, c);
  assert.equal(e3?.meta.title, "appended");
  assert.equal(c.headReuses, 1);
  const appended = (await fs.stat(file)).size - e2!.size;
  // the tail window (the head has no cwd), the appended bytes, and the probes around the one title line found in them
  assert.ok(c.bytesRead - afterFirst <= TAIL_BYTES + 3 * appended + 1, `read ${c.bytesRead - afterFirst} bytes`);
});

test("a replaced file (new inode) is read from the start again", async () => {
  const file = await tmpFile();
  await fs.writeFile(file, jl([{ type: "x", cwd: "/old" }, ...Array.from({ length: HEAD_MAX_LINES + 5 }, (_, i) => filler(i))]));
  const c = newReadCounters();
  const e1 = await readTranscriptMeta(file, undefined, c);
  assert.equal(e1?.meta.cwd, "/old");
  const tmp = file + ".new";
  await fs.writeFile(tmp, jl([{ type: "x", cwd: "/new" }, ...Array.from({ length: HEAD_MAX_LINES + 50 }, (_, i) => filler(i))]));
  await fs.rename(tmp, file);
  const e2 = await readTranscriptMeta(file, e1 ?? undefined, c);
  assert.equal(e2?.meta.cwd, "/new");
  assert.equal(c.headReuses, 0);
});

test("broken lines are counted and skipped; an unterminated last line counts as partial", async () => {
  const file = await tmpFile();
  await fs.writeFile(file, '{"type":"x","cwd":"/w"}\nnot json\n[1,2]\n{"type":"ai-title","aiTitle":"ok"}\n{"type":"ai-title","ai');
  const c = newReadCounters();
  const e = await readTranscriptMeta(file, undefined, c);
  assert.equal(e?.meta.cwd, "/w");
  assert.equal(e?.meta.title, "ok");
  assert.equal(c.badJsonLines, 2);
  assert.equal(c.partialLines, 1);
});

test("a missing file returns null", async () => {
  const file = await tmpFile("gone.jsonl");
  assert.equal(await readTranscriptMeta(file, undefined, newReadCounters()), null);
});
