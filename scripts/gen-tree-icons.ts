// Writes apps/web/src/components/files/treeIconData.ts, the file tree's icons (DESIGN.md 6e), from
// a T3 Code clone with its dependencies installed: @pierre/trees (dist/builtInIcons.js, the copy
// T3's web app installs) and T3's apps/web/src/pierre-icons.ts.
//   node scripts/gen-tree-icons.ts <t3code clone>
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const t3 = process.argv[2];
if (!t3) throw new Error("usage: node scripts/gen-tree-icons.ts <t3code clone>");
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../apps/web/src/components/files/treeIconData.ts");
const pierreDist = path.join(t3, "apps/web/node_modules/@pierre/trees/dist");
const pierrePkg = JSON.parse(fs.readFileSync(path.join(pierreDist, "../package.json"), "utf8")) as { version: string };
const builtInPath = path.join(pierreDist, "builtInIcons.js");
const builtIn = (await import(pathToFileURL(builtInPath).href)) as { getBuiltInSpriteSheet: (set: string) => string };
const builtInSource = fs.readFileSync(builtInPath, "utf8");

/** Evaluates an object literal copied from a source file. */
function evaluate(literal: string): Record<string, string> {
  return Function(`"use strict"; return (${literal});`)() as Record<string, string>;
}

/** A `const NAME = {...};` literal from the built file. */
function builtInLiteral(name: string): Record<string, string> {
  const m = new RegExp(`const ${name} = ([\\s\\S]*?);\\n`).exec(builtInSource);
  if (!m) throw new Error(`missing ${name}`);
  return evaluate(m[1]!.replace("/* @__PURE__ */ ", ""));
}

const fileNameTokens = builtInLiteral("BUILT_IN_FILE_NAME_TOKENS");
const extensionTokens = builtInLiteral("BUILT_IN_FILE_EXTENSION_TOKENS");
const completeOverrides = builtInLiteral("COMPLETE_EXTENSION_OVERRIDES");
// The "complete" set: every built-in symbol (chevron, file, the language marks).
const pierreSprite = builtIn.getBuiltInSpriteSheet("complete");

const t3Source = fs.readFileSync(path.join(t3, "apps/web/src/pierre-icons.ts"), "utf8");
const t3SpriteMatch = /const T3_FILE_ICON_SPRITE = `([\s\S]*?)`;/.exec(t3Source);
const documentColors = /const DOCUMENT_ICON_COLORS[^=]*= (\{[\s\S]*?\});/.exec(t3Source);
const byNameMatch = /byFileName: (\{[\s\S]*?\}),\n  byFileExtension/.exec(t3Source);
const byExtMatch = /byFileExtension: \{\n    \.\.\.Object\.fromEntries\([\s\S]*?\n    \),\n([\s\S]*?)\n  \},\n\} satisfies/.exec(t3Source);
if (!t3SpriteMatch || !documentColors || !byNameMatch || !byExtMatch) throw new Error("pierre-icons.ts changed shape");
const documentColorMap = evaluate(documentColors[1]!);
// The document symbols interpolate DOCUMENT_ICON_COLORS; resolve them here.
const t3Sprite = t3SpriteMatch[1]!.replace(/\$\{DOCUMENT_ICON_COLORS\["([^"]+)"\]\}/g, (_, k: string) => {
  const color = documentColorMap[k];
  if (!color) throw new Error(`missing color ${k}`);
  return color;
});
// Symbols only, without T3's wrapper <svg>: they join Pierre's sheet.
const t3Symbols = t3Sprite.replace(/^\s*<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
const t3ByName = evaluate(byNameMatch[1]!);
const t3ByExt = evaluate(`{${byExtMatch[1]!}}`);
// T3 spreads @t3tools/shared/video VIDEO_FILE_EXTENSIONS first.
for (const ext of ["avi", "m4v", "mkv", "mov", "mp4", "ogv", "webm"]) t3ByExt[ext] = "t3-file-icon-video";

const sprite = pierreSprite.replace("</svg>", `\n  ${t3Symbols.split("\n").join("\n  ")}\n</svg>`);
const json = (v: unknown) => JSON.stringify(v, null, 2);

const text = `// Generated by scripts/gen-tree-icons.ts; do not edit by hand. From @pierre/trees ${pierrePkg.version},
// Copyright 2025 Pierre Computer Company, Apache License 2.0, dist/builtInIcons.js: the
// "complete" sprite sheet and its file name and extension tokens. Also adapted from T3 Code
// (https://github.com/pingdotgg/t3code), MIT License, Copyright (c) 2026 T3 Tools Inc.:
// apps/web/src/pierre-icons.ts (T3_FILE_ICON_SPRITE, whose language logos come from Simple Icons,
// CC0, and icons from Lucide, ISC, and the byFileName and byFileExtension rules of
// T3_PIERRE_ICONS). See THIRD_PARTY_NOTICES.md.

/** Every symbol a tree row references with \`<use href="#id">\`; mounted once (ensureTreeIconSprite). */
export const TREE_ICON_SPRITE = ${JSON.stringify(sprite)};

/** T3_PIERRE_ICONS.byFileName (lowercase names). */
export const T3_ICON_BY_FILE_NAME: Readonly<Record<string, string>> = ${json(t3ByName)};

/** T3_PIERRE_ICONS.byFileExtension. */
export const T3_ICON_BY_FILE_EXTENSION: Readonly<Record<string, string>> = ${json(t3ByExt)};

/** Pierre BUILT_IN_FILE_NAME_TOKENS. */
export const BUILT_IN_FILE_NAME_TOKENS: Readonly<Record<string, string>> = ${json(fileNameTokens)};

/** Pierre BUILT_IN_FILE_EXTENSION_TOKENS. */
export const BUILT_IN_FILE_EXTENSION_TOKENS: Readonly<Record<string, string>> = ${json(extensionTokens)};

/** Pierre COMPLETE_EXTENSION_OVERRIDES. */
export const COMPLETE_EXTENSION_OVERRIDES: Readonly<Record<string, string>> = ${json(completeOverrides)};
`;
fs.writeFileSync(out, text);
console.log(`wrote ${out}: sprite ${sprite.length} chars, ${(sprite.match(/<symbol /g) ?? []).length} symbols`);
